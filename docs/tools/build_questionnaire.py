def f(size=10, bold=False, color="000000", italic=False):
    return Font(name=FONT, size=size, bold=bold, color=color, italic=italic)


def fill(hex_):
    return PatternFill("solid", start_color=hex_, end_color=hex_)


def est_lines(text, width):
    """ประมาณจำนวนบรรทัดของข้อความที่ wrap ในคอลัมน์กว้าง width"""
    if text is None:
        return 1
    chars_per_line = max(width * 1.1, 1)
    lines = 0
    for part in str(text).split("\n"):
        lines += max(1, math.ceil(len(part) / chars_per_line))
    return lines


def fit_row(ws, row, widths, min_lines=1, line_h=16):
    lines = min_lines
    for col_idx, w in enumerate(widths, start=1):
        lines = max(lines, est_lines(ws.cell(row=row, column=col_idx).value, w))
    ws.row_dimensions[row].height = lines * line_h + 6


def set_widths(ws, widths):
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def title_block(ws, title, subtitle, ncols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncols)
    c = ws.cell(row=1, column=1, value=title)
    c.font = f(14, True, "FFFFFF")
    c.fill = fill(C_TITLE)
    c.alignment = Alignment(vertical="center", indent=1)
    ws.row_dimensions[1].height = 30
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncols)
    c = ws.cell(row=2, column=1, value=subtitle)
    c.font = f(10, color="5A4636")
    c.alignment = Alignment(wrap_text=True, vertical="center", indent=1)
    return 4  # แถวหัวตาราง


def header_row(ws, row, headers):
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = f(10, True)
        c.fill = fill(C_HEAD)
        c.alignment = WRAP_CENTER
        c.border = BORDER
    ws.row_dimensions[row].height = 34


