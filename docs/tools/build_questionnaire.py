# --- แท็บแม่แบบ ---------------------------------------------------------------
def template_sheet(name, title, subtitle, columns, example_rows, blank_rows=40, validations=None):
    """columns: list of (header, width); example_rows: list of lists"""
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = False
    widths = [w for _, w in columns]
    set_widths(ws, widths)
    hr = title_block(ws, title, subtitle, len(columns))
    ws.row_dimensions[2].height = 34
    header_row(ws, hr, [h for h, _ in columns])
    ws.freeze_panes = ws.cell(row=hr + 1, column=1)
    r = hr + 1
    for ex in example_rows:
        for col, v in enumerate(ex, start=1):
            cell = ws.cell(row=r, column=col, value=v)
            cell.font = f(9, italic=True, color="7F7F7F")
            cell.fill = fill(C_EXAMPLE)
            cell.border = BORDER
            cell.alignment = WRAP_TOP
        fit_row(ws, r, widths)
        r += 1
    first_input = r
    for _ in range(blank_rows):
        for col in range(1, len(columns) + 1):
            cell = ws.cell(row=r, column=col)
            cell.fill = fill(C_INPUT)
            cell.border = BORDER
            cell.font = f(10)
            cell.alignment = WRAP_TOP
        ws.row_dimensions[r].height = 22
        r += 1
    last_input = r - 1
    for col_idx, options in (validations or {}).items():
        dv = DataValidation(type="list", formula1='"' + ",".join(options) + '"', allow_blank=True,
                            showErrorMessage=False)
        dv.promptTitle = "เลือกจากรายการ"
        dv.prompt = "เลือกจากรายการ หรือพิมพ์เองก็ได้"
        dv.showInputMessage = True
        letter = get_column_letter(col_idx)
        dv.add(f"{letter}{first_input}:{letter}{last_input}")
        ws.add_data_validation(dv)
    return ws


